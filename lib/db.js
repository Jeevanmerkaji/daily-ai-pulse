// lib/db.js
//
// Everything the app does with the database goes through this one file.
// There's no ORM here on purpose — just plain SQL — so you can read every
// query top to bottom and know exactly what it does, instead of learning a
// separate query-building library.

import pg from "pg";
import { DEFAULT_TOPIC } from "./topics.js";

const { Pool, types } = pg;

// By default, node-postgres turns Postgres DATE columns into JS Date
// objects — but it does that using the server's local timezone, which can
// silently shift the date by a day depending on where the code runs. Since
// we only ever store simple "YYYY-MM-DD" values, we tell it to just hand us
// the raw string instead (1082 is Postgres's internal type ID for DATE).
types.setTypeParser(1082, (value) => value);

// A "Pool" is a small set of reusable database connections. Instead of
// opening a brand new connection every time we talk to Postgres (slow), we
// borrow one from the pool, use it, and give it back.
const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  // Neon (and most hosted Postgres providers) require SSL. `rejectUnauthorized: false`
  // keeps this simple for an MVP; it still encrypts the connection.
  ssl: { rejectUnauthorized: false },
});

// ---- daily_stories ----
//
// Every function here defaults to the "general" topic, so all the existing
// callers (the public /today and /archive pages) that don't know or care
// about topics keep working completely unchanged.

// Insert today's story for a topic, or update it if one for that
// date+topic already exists (e.g. you re-run the job manually). "Upsert" =
// update-or-insert.
export async function saveStory({ date, topic = DEFAULT_TOPIC, headline, summary, sourceUrl, sourceName }) {
  const result = await pool.query(
    `INSERT INTO daily_stories (date, topic, headline, summary, source_url, source_name)
     VALUES ($1, $2, $3, $4, $5, $6)
     ON CONFLICT (date, topic)
     DO UPDATE SET headline = $3, summary = $4, source_url = $5, source_name = $6
     RETURNING *`,
    [date, topic, headline, summary, sourceUrl, sourceName]
  );
  return result.rows[0];
}

// Most recent story for a topic — used by the "today" page.
export async function getLatestStory(topic = DEFAULT_TOPIC) {
  const result = await pool.query(
    `SELECT * FROM daily_stories WHERE topic = $1 ORDER BY date DESC LIMIT 1`,
    [topic]
  );
  return result.rows[0] || null;
}

// One story by its date and topic (used by the archive detail page).
// `date` is a "YYYY-MM-DD" string.
export async function getStoryByDate(date, topic = DEFAULT_TOPIC) {
  const result = await pool.query(
    `SELECT * FROM daily_stories WHERE date = $1 AND topic = $2`,
    [date, topic]
  );
  return result.rows[0] || null;
}

// All stories for a topic, most recent first — used by the archive list page.
export async function getAllStories(topic = DEFAULT_TOPIC) {
  const result = await pool.query(
    `SELECT * FROM daily_stories WHERE topic = $1 ORDER BY date DESC`,
    [topic]
  );
  return result.rows;
}

// ---- users (subscribers + accounts) ----

// Add a new subscriber. `unsubscribeToken` is generated by the caller
// (crypto.randomUUID()) so it's easy to test without touching the DB layer.
// If the email already exists, we just re-activate it instead of erroring.
export async function addSubscriber(email, unsubscribeToken) {
  const result = await pool.query(
    `INSERT INTO users (email, unsubscribe_token)
     VALUES ($1, $2)
     ON CONFLICT (email)
     DO UPDATE SET active = true
     RETURNING *`,
    [email, unsubscribeToken]
  );
  return result.rows[0];
}

// Everyone who should receive today's email.
export async function getActiveSubscribers() {
  const result = await pool.query(
    `SELECT * FROM users WHERE active = true`
  );
  return result.rows;
}

// Flip a subscriber to inactive using the token from their unsubscribe link.
// Returns the user row if the token matched, or null if it didn't (e.g. a
// broken/tampered link).
export async function deactivateByToken(token) {
  const result = await pool.query(
    `UPDATE users SET active = false WHERE unsubscribe_token = $1 RETURNING *`,
    [token]
  );
  return result.rows[0] || null;
}

// Changes which topic's daily story a user receives.
export async function updateUserTopic(userId, topic) {
  const result = await pool.query(
    `UPDATE users SET topic = $1 WHERE id = $2 RETURNING *`,
    [topic, userId]
  );
  return result.rows[0];
}

// ---- billing (Stripe) ----

// Called once, right after someone's first successful checkout. Marks them
// as a paying "pro" user and remembers their Stripe ids so future webhook
// events (and the billing portal) can find them again.
export async function setUserBillingOnCheckoutComplete(userId, { stripeCustomerId, stripeSubscriptionId }) {
  const result = await pool.query(
    `UPDATE users
     SET plan = 'pro', stripe_customer_id = $1, stripe_subscription_id = $2
     WHERE id = $3
     RETURNING *`,
    [stripeCustomerId, stripeSubscriptionId, userId]
  );
  return result.rows[0];
}

// Called whenever Stripe tells us a subscription's status changed
// (renewed, payment failed, canceled). `plan` should already be resolved
// to 'pro' or 'free' by the caller based on Stripe's status string.
export async function updateUserPlanBySubscriptionId(subscriptionId, plan) {
  const result = await pool.query(
    `UPDATE users SET plan = $1 WHERE stripe_subscription_id = $2 RETURNING *`,
    [plan, subscriptionId]
  );
  return result.rows[0] || null;
}

// ---- accounts (magic-link login) ----

// Called when someone requests a login link. If the email has never been
// seen before, this creates a brand-new (inactive — logging in doesn't
// automatically subscribe them to the daily email) account for them. Either
// way, it sets a fresh login token, overwriting any previous pending one so
// only the most recently requested link can ever work.
export async function setLoginToken(email, { unsubscribeToken, loginToken, loginTokenExpiresAt }) {
  const result = await pool.query(
    `INSERT INTO users (email, active, unsubscribe_token, login_token, login_token_expires_at)
     VALUES ($1, false, $2, $3, $4)
     ON CONFLICT (email)
     DO UPDATE SET login_token = $3, login_token_expires_at = $4
     RETURNING *`,
    [email, unsubscribeToken, loginToken, loginTokenExpiresAt]
  );
  return result.rows[0];
}

// Looks up the user a login link's token belongs to — but only if that
// token hasn't expired yet. Returns null for a missing, wrong, or expired
// token, so callers don't need to separately check expiry.
export async function getUserByValidLoginToken(token) {
  const result = await pool.query(
    `SELECT * FROM users WHERE login_token = $1 AND login_token_expires_at > now()`,
    [token]
  );
  return result.rows[0] || null;
}

// Called right after a login link is used, so the same link can't be used
// twice.
export async function clearLoginToken(userId) {
  await pool.query(
    `UPDATE users SET login_token = NULL, login_token_expires_at = NULL WHERE id = $1`,
    [userId]
  );
}

// ---- sessions ----

export async function createSession(userId, token, expiresAt) {
  await pool.query(
    `INSERT INTO sessions (token, user_id, expires_at) VALUES ($1, $2, $3)`,
    [token, userId, expiresAt]
  );
}

// Looks up who's logged in from their session cookie's value, in one query.
// Returns null if there's no session, or it's expired.
export async function getSessionWithUser(token) {
  const result = await pool.query(
    `SELECT users.* FROM sessions
     JOIN users ON users.id = sessions.user_id
     WHERE sessions.token = $1 AND sessions.expires_at > now()`,
    [token]
  );
  return result.rows[0] || null;
}

export async function deleteSession(token) {
  await pool.query(`DELETE FROM sessions WHERE token = $1`, [token]);
}

// Simple housekeeping so the sessions table doesn't grow forever. Cheap
// enough to call once a day from the daily job rather than needing its own
// schedule.
export async function deleteExpiredSessions() {
  await pool.query(`DELETE FROM sessions WHERE expires_at < now()`);
}
