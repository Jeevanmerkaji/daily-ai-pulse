// lib/db.js
//
// Everything the app does with the database goes through this one file.
// There's no ORM here on purpose — just plain SQL — so you can read every
// query top to bottom and know exactly what it does, instead of learning a
// separate query-building library.

import pg from "pg";

const { Pool, types } = pg;

// By default, node-postgres turns Postgres DATE columns into JS Date
// objects — but it does that using the server's local timezone, which can
// silently shift the date by a day depending on where the code runs. Since
// we only ever store simple "YYYY-MM-DD" values, we tell it to just hand us
// the raw string instead (1082 is Postgres's internal type ID for DATE).
types.setTypeParser(1082, (value) => value);

// A "Pool" is a small set of reusable database connections. Instead of
// opening a brand new connection every time we talk to Postgres (slow), we
// borrow one from the pool, use it, and give it back.
const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  // Neon (and most hosted Postgres providers) require SSL. `rejectUnauthorized: false`
  // keeps this simple for an MVP; it still encrypts the connection.
  ssl: { rejectUnauthorized: false },
});

// ---- daily_stories ----

// Insert today's story, or update it if a story for that date already exists
// (e.g. you re-run the job manually). "Upsert" = update-or-insert.
export async function saveStory({ date, headline, summary, sourceUrl, sourceName }) {
  const result = await pool.query(
    `INSERT INTO daily_stories (date, headline, summary, source_url, source_name)
     VALUES ($1, $2, $3, $4, $5)
     ON CONFLICT (date)
     DO UPDATE SET headline = $2, summary = $3, source_url = $4, source_name = $5
     RETURNING *`,
    [date, headline, summary, sourceUrl, sourceName]
  );
  return result.rows[0];
}

// Most recent story — used by the "today" page.
export async function getLatestStory() {
  const result = await pool.query(
    `SELECT * FROM daily_stories ORDER BY date DESC LIMIT 1`
  );
  return result.rows[0] || null;
}

// One story by its date (used by the archive detail page). `date` is a
// "YYYY-MM-DD" string.
export async function getStoryByDate(date) {
  const result = await pool.query(
    `SELECT * FROM daily_stories WHERE date = $1`,
    [date]
  );
  return result.rows[0] || null;
}

// All stories, most recent first — used by the archive list page.
export async function getAllStories() {
  const result = await pool.query(
    `SELECT * FROM daily_stories ORDER BY date DESC`
  );
  return result.rows;
}

// ---- subscribers ----

// Add a new subscriber. `unsubscribeToken` is generated by the caller
// (crypto.randomUUID()) so it's easy to test without touching the DB layer.
// If the email already exists, we just re-activate it instead of erroring.
export async function addSubscriber(email, unsubscribeToken) {
  const result = await pool.query(
    `INSERT INTO subscribers (email, unsubscribe_token)
     VALUES ($1, $2)
     ON CONFLICT (email)
     DO UPDATE SET active = true
     RETURNING *`,
    [email, unsubscribeToken]
  );
  return result.rows[0];
}

// Everyone who should receive today's email.
export async function getActiveSubscribers() {
  const result = await pool.query(
    `SELECT * FROM subscribers WHERE active = true`
  );
  return result.rows;
}

// Flip a subscriber to inactive using the token from their unsubscribe link.
// Returns the subscriber row if the token matched, or null if it didn't
// (e.g. a broken/tampered link).
export async function deactivateByToken(token) {
  const result = await pool.query(
    `UPDATE subscribers SET active = false WHERE unsubscribe_token = $1 RETURNING *`,
    [token]
  );
  return result.rows[0] || null;
}
